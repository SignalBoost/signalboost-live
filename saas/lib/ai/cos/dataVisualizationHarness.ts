/**
 * COS data-visualization orchestration seam.
 *
 * Every structured chart capability uses the same host-owned sequence:
 * plan -> acquire evidence -> verify evidence -> deliver chart + provenance.
 * The LLM may ask for an output but cannot create data points, bypass checks,
 * charge for synthetic-image generation, or turn failed retrieval into success.
 *
 * The first registered adapter is historical financial series. Other structured
 * data domains plug in here instead of adding separate image-routing exceptions.
 */
import { resolveHistoricalStockChartIntent } from './historicalStockChartIntent.ts'
import { loadHistoricalStockPrices, verifyHistoricalPriceCoverage } from './historicalStockChart.ts'
import type { HistoricalPrices } from './historicalStockChart.ts'

type Turn = Readonly<{role?: unknown; content?: unknown}>
type Status = 'completed' | 'evidence_unavailable' | 'evidence_rejected'

export type DataVisualizationReceipt = Readonly<{
  capability: 'data_visualization.historical_financial_series'
  status: Status
  symbol: string
  range: string
  evidence_source?: string
  source_url?: string
  checked_at: string
  observation_count?: number
  first_observation?: string
  last_observation?: string
  checks: readonly string[]
}>

export type DataVisualizationResult = Readonly<{
  status: Status
  reply: string
  source: 'cos-historical-stock-chart' | 'cos-historical-chart-data-unavailable'
  receipt: DataVisualizationReceipt
}>

function observe(stage: string, info: Record<string, string | number | boolean>) {
  // Production logs contain only capability labels, public ticker/range,
  // lifecycle and verification counts; never prompts, account IDs or private data.
  console.info('[cos-capability-harness]', JSON.stringify({ capability:'data_visualization',stage,...info }))
}

function completedMessage(history: HistoricalPrices, origin: string): string {
  const first=history.points[0]
  const last=history.points[history.points.length-1]
  const delta=(last.close/first.close-1)*100
  const range=history.range
  const chartUrl=new URL('/api/market-charts/'+encodeURIComponent(history.symbol)+'.svg?range='+encodeURIComponent(range),origin).toString()
  return [
    '**'+history.symbol+' — historical closing prices ('+range+')**',
    chartUrl,
    'From '+first.date+' through '+last.date+': '+history.currency+' '+first.close.toFixed(2)+
      ' to '+last.close.toFixed(2)+' ('+(delta>=0?'+':'')+delta.toFixed(2)+'%). '+history.points.length+' observed closing prices.',
    'Data source: ['+history.source+']('+history.sourceUrl+'). Dated prices are plotted from the source, not generated by AI. Not a forecast.',
  ].join('\n\n')
}

/**
 * Capability admission and fulfillment are host-owned. A matching plan means
 * the current requested deliverable is a data chart, NOT synthetic artwork.
 * On provider failure, return a transparent blocker rather than routing into
 * the paid image generator or inventing prices from one live quote.
 */
export async function orchestrateDataVisualization(
  turns: readonly Turn[],
  origin: string,
  options: { fetchImpl?: typeof fetch; now?: Date } = {},
): Promise<DataVisualizationResult | null> {
  const plan=resolveHistoricalStockChartIntent(turns)
  if (!plan) return null
  const started=Date.now()
  const capability: DataVisualizationReceipt['capability']='data_visualization.historical_financial_series'
  observe('plan',{kind:capability,range:plan.range,symbol:plan.symbol})
  let prices: HistoricalPrices | null = null
  try {
    prices=await loadHistoricalStockPrices(plan.symbol,plan.range,options.fetchImpl,options.now)
  } catch { prices=null }
  const checkedAt=(options.now||new Date()).toISOString()
  if (!prices) {
    observe('blocked',{kind:capability,reason:'evidence_unavailable',elapsed_ms:Date.now()-started})
    return {
      status:'evidence_unavailable',
      source:'cos-historical-chart-data-unavailable',
      receipt:{capability,status:'evidence_unavailable',symbol:plan.symbol,range:plan.range,checked_at:checkedAt,checks:['independent_dated_source_required','no_invented_prices','no_image_generation']},
      reply:'I could not retrieve a usable historical price series for '+plan.symbol+
        '. A single current quote cannot establish a historical trend. You can inspect historical data at '+
        'https://finance.yahoo.com/quote/'+encodeURIComponent(plan.symbol)+'/history/.',
    }
  }
  const verification=verifyHistoricalPriceCoverage(prices,options.now||new Date())
  if (!verification.ok) {
    observe('blocked',{kind:capability,reason:'evidence_rejected',elapsed_ms:Date.now()-started})
    return {
      status:'evidence_rejected',
      source:'cos-historical-chart-data-unavailable',
      receipt:{capability,status:'evidence_rejected',symbol:plan.symbol,range:plan.range,checked_at:checkedAt,checks:['source_cannot_support_requested_window','no_invented_prices','no_image_generation']},
      reply:'The retrieved historical records for '+plan.symbol+' do not adequately cover the requested '+plan.range+
        ' period. I will not present an incomplete chart as six months of market performance.',
    }
  }
  const first=prices.points[0],last=prices.points[prices.points.length-1]
  const receipt:DataVisualizationReceipt={
    capability,status:'completed',symbol:prices.symbol,range:plan.range,
    evidence_source:prices.source,source_url:prices.sourceUrl,checked_at:checkedAt,
    observation_count:prices.points.length,first_observation:first.date,last_observation:last.date,
    checks:['dated_source_verified','range_coverage_verified','data_driven_render','no_image_generation'],
  }
  observe('completed',{kind:capability,source:prices.source,points:prices.points.length,elapsed_ms:Date.now()-started})
  return {status:'completed',reply:completedMessage(prices,origin),source:'cos-historical-stock-chart',receipt}
}
