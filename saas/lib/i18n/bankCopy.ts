/** Resolve a bank copy string for a language (with English fallback). */
export function bankCopy(lang: string | undefined, path: string): string | undefined {
  const safe = typeof lang === 'string' ? lang : 'en'
  return (BANK_COPY[safe] && BANK_COPY[safe][path]) || BANK_COPY.en[path]
}
