-- Durable append-only history for buyer-grade University throughput and recovery evidence.
create table if not exists public.cos_university_lifecycle_transition_history (
  id bigint generated by default as identity primary key,
  candidate_id text not null,
  artifact_hash text not null,
  subject_id text,
  from_station text,
  to_station text not null,
  from_status text,
  to_status text not null,
  entered_from_at timestamptz,
  transitioned_at timestamptz not null default now(),
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  was_overdue boolean not null default false,
  last_error text,
  authority_expanded boolean not null default false,
  unique (candidate_id, artifact_hash, to_station, transitioned_at)
);
create index if not exists cos_university_lifecycle_transition_history_time_idx on public.cos_university_lifecycle_transition_history (transitioned_at desc);
create index if not exists cos_university_lifecycle_transition_history_station_idx on public.cos_university_lifecycle_transition_history (from_station, transitioned_at desc);
revoke all on public.cos_university_lifecycle_transition_history from public, anon, authenticated;
grant select, insert on public.cos_university_lifecycle_transition_history to service_role;
