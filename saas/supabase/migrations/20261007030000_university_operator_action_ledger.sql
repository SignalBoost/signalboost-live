-- Step 1 "no manual intervention" evidence (2026-10-07).
--
-- ONBOARD Step 1 exit criterion: "the line repeatedly moving without manual intervention". Until now no table recorded who
-- moved a unit, so the Step 1 report could only say not_measured. Two sources of manual action are recorded here:
--
--   database_session  a row of a factory table written by any session other than the platform's. The platform reaches the
--                     database only through PostgREST, whose session_user is always 'authenticator' (service_role and RPC
--                     calls included; SECURITY DEFINER functions change current_user, never session_user). Any other
--                     session user (SQL editor, psql, dashboard table editor) is a person acting on the line directly.
--   admin_route       an owner-authenticated admin API action, written by the application itself.
--
-- The trigger only reads session_user and returns at once for the platform's own writes. It never blocks or alters a
-- write. Read only by the Step 1 evidence report (service_role).

create table if not exists public.cos_university_operator_actions (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  source text not null check (source in ('ledger_installed', 'database_session', 'admin_route')),
  actor text not null,
  target text not null,
  operation text not null,
  candidate_id text,
  artifact_hash text
);

create index if not exists cos_university_operator_actions_time_idx
  on public.cos_university_operator_actions (occurred_at desc);

revoke all on public.cos_university_operator_actions from public, anon, authenticated;
grant select, insert on public.cos_university_operator_actions to service_role;

create or replace function public.cos_university_record_operator_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  row_data jsonb;
begin
  if session_user = 'authenticator' then
    return null;
  end if;
  row_data := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
  insert into public.cos_university_operator_actions (source, actor, target, operation, candidate_id, artifact_hash)
  values (
    'database_session',
    session_user::text,
    tg_table_name,
    lower(tg_op),
    left(row_data ->> 'candidate_id', 240),
    left(coalesce(row_data ->> 'trained_artifact_hash', row_data ->> 'artifact_hash'), 64)
  );
  return null;
end;
$$;

revoke all on function public.cos_university_record_operator_write() from public, anon, authenticated;

do $$
declare
  factory_table text;
begin
  foreach factory_table in array array[
    'cos_local_distillation_artifacts',
    'cos_university_artifact_birth_certificates',
    'cos_university_mass_distillation_batch_runs',
    'cos_university_distilled_evaluation_runs',
    'cos_university_learning_assurance_events',
    'cos_university_residency_enrollments',
    'cos_university_residency_case_runs',
    'cos_university_graduate_model_registry',
    'cos_university_lifecycle_orchestration'
  ] loop
    execute format('drop trigger if exists cos_university_operator_write on public.%I', factory_table);
    execute format(
      'create trigger cos_university_operator_write after insert or update or delete on public.%I '
      'for each row execute function public.cos_university_record_operator_write()',
      factory_table
    );
  end loop;
end;
$$;

-- The report measures manual intervention only from this moment on; earlier windows are reported as partial.
insert into public.cos_university_operator_actions (source, actor, target, operation)
values ('ledger_installed', session_user::text, 'cos_university_operator_actions', 'install');
