create table if not exists public.cos_quality_repair_decisions (
  id bigint generated by default as identity primary key,
  repair_kind text not null check (repair_kind in ('quality_repair', 'skill_citation_repair')),
  reasoner_label text not null,
  accepted boolean not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists cos_quality_repair_decisions_kind_time_idx on public.cos_quality_repair_decisions(repair_kind, created_at desc);
alter table public.cos_quality_repair_decisions enable row level security;
